// Idempotent pre-build step: makes sure the bundled R runtime exists so that
// `pnpm tauri build` works on a fresh clone.

const fs = require("fs");
const path = require("path");
const { spawnSync } = require("child_process");

const ROOT = path.resolve(__dirname, "..");
const RUNTIME_DIR = path.join(ROOT, "src-tauri", "r-runtime");
const IS_WINDOWS = process.platform === "win32";

function writePlaceholder() {
    fs.mkdirSync(RUNTIME_DIR, { recursive: true });
    const placeholder = path.join(RUNTIME_DIR, "README.txt");
    if (!fs.existsSync(placeholder)) {
        fs.writeFileSync(
            placeholder,
            "Bundled R runtime for the shoeprint comparison feature.\n" +
                "Generated by scripts/build-r-runtime.cjs -- do not edit by hand.\n"
        );
    }
}

const markers = [path.join(RUNTIME_DIR, "library", "shoeprintr")];
if (IS_WINDOWS) {
    markers.push(path.join(RUNTIME_DIR, "bin", "x64", "Rscript.exe"));
}

const missing = markers.filter(marker => !fs.existsSync(marker));

if (missing.length === 0) {
    writePlaceholder();
    console.log(`R runtime already present: ${RUNTIME_DIR}`);
    process.exit(0);
}

console.log("R runtime missing, building it now...");
const result = spawnSync("node", [path.join(__dirname, "build-r-runtime.cjs")], {
    stdio: "inherit",
    shell: false,
});

const status = result.status === null ? 1 : result.status;
writePlaceholder();

if (status !== 0 && !IS_WINDOWS) {
    console.warn(
        "\nWARNING: the R runtime could not be prepared.\n" +
            "The build will continue, but shoeprint comparison will report the\n" +
            "analysis engine as unavailable. Install R and re-run `pnpm r:build`\n" +
            "to enable it.\n"
    );
    process.exit(0);
}

process.exit(status);
